import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { J, finish, ok, startBot, until } from './harness.mjs';
const bot = await startBot();
await bot.mention('UMEM', 'first message');
const thread = bot.lastTs;
const firstId = JSON.parse(readFileSync(path.join(bot.dir, 'sessions', readdirSync(path.join(bot.dir, 'sessions'))[0]))).responseId;
await bot.mention('UMEM', 'follow up', thread);
ok(bot.agentCalls().at(-1).previous_response_id === firstId, 'same user and thread continues memory');
await bot.mention('UADMIN', 'another user', thread);
ok(!bot.agentCalls().at(-1).previous_response_id, 'another user gets a separate response chain');
ok(!JSON.stringify(bot.gateway.requests).includes(process.env.SLACK_BOT_TOKEN), 'Slack credentials never reach the gateway');
await bot.dm('UMEM', 'answer my DM');
ok(bot.calls.some(c => c.m === 'chat.update' && c.a.channel === 'D0DM'), 'DMs are answered');
const count = bot.gateway.requests.length;
await bot.mention('UNOBODY', 'please answer');
ok(bot.gateway.requests.length === count, 'unlisted user cannot reach the gateway');
bot.setMode('file');
await bot.mention('UMEM', 'make CSV');
ok(bot.calls.some(c => c.m === 'files.uploadV2' && c.a.file_uploads?.some(f => f.filename === 'result.csv')), 'generated text files are delivered');
const uploads = bot.calls.filter(c => c.m === 'files.uploadV2').length;
await bot.mention('UVIEW', 'make CSV');
bot.setMode('long');
await bot.mention('UVIEW', 'give a long answer');
ok(bot.calls.filter(c => c.m === 'files.uploadV2').length === uploads, 'viewer cannot receive files, including automatic long-answer attachments');
ok(bot.agentCalls().at(-1).tools.length === 0, 'viewer has no web tools');
// File bytes cross the gateway only as extracted text or data-URL images.
bot.setMode('complete');
const realFetch = globalThis.fetch;
let downloaded = 0;
globalThis.fetch = async (url, options) => {
  downloaded++;
  ok(options.headers.Authorization === `Bearer ${process.env.SLACK_BOT_TOKEN}`, 'Slack token is used only for authenticated file download');
  return new Response(url.endsWith('.png') ? Buffer.from([137,80,78,71]) : 'attachment content', { headers: { 'content-type': 'application/octet-stream' } });
};
await bot.mention('UMEM', 'read attached file', undefined, [{ id: 'F1', name: 'notes.txt', url_private: 'https://files.slack.com/notes.txt', size: 18 }]);
const nativeFile = bot.agentCalls().at(-1).input[0].content.find(part => part.type === 'input_file');
ok(nativeFile && Buffer.from(nativeFile.file_data.split(',')[1], 'base64').toString() === 'attachment content', 'text upload uses native input_file content');
await bot.mention('UMEM', 'describe attached image', undefined, [{ id: 'F2', name: 'photo.png', url_private: 'https://files.slack.com/photo.png', size: 4 }]);
ok(bot.agentCalls().at(-1).input[0].content.some(part => part.type === 'input_image' && part.image_url.startsWith('data:image/png;base64,')), 'image upload uses Responses input_image data URL');
await bot.mention('UMEM', 'read external file', undefined, [{ id: 'F3', name: 'bad.txt', url_private: 'https://example.org/bad.txt', size: 4 }]);
ok(downloaded === 2, 'file download never sends Slack credentials to another host');
globalThis.fetch = realFetch;
ok(readdirSync(path.join(bot.dir, 'inputs')).length === 0, 'temporary uploads are removed after the job');
bot.setMode('slowchat');
const running = bot.mention('UMEM', 'slow request');
await until(() => /slow request/.test(bot.agentCalls().at(-1).prompt));
const pending = [...bot.calls].reverse().find(c => c.m === 'chat.postMessage' && /cancel_job/.test(J(c.a.blocks)));
const id = pending.a.blocks.find(b => b.type === 'actions').elements[0].value;
await bot.click('cancel_job', id, 'UVIEW');
ok(bot.ephemerals().some(text => /Only the person who asked/.test(text)), 'other members cannot cancel a request');
await bot.click('cancel_job', id, 'UMEM');
await running;
ok(Boolean(bot.lastUpdate(a => /Cancelled/.test(J(a.blocks)))), 'owner cancellation closes the WebSocket request');
writeFileSync(path.join(bot.dir, 'access.json'), '{invalid');
const before = bot.gateway.requests.length;
await bot.mention('UMEM', 'after invalid access edit');
ok(bot.gateway.requests.length === before, 'invalid access policy fails closed');
ok(bot.calls.filter(c => ['chat.postMessage', 'chat.postEphemeral'].includes(c.m)).every(c => c.a.thread_ts && !c.a.reply_broadcast), 'answers, chunks, and access notices stay in threads');
finish();
