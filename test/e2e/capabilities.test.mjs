import { J, finish, ok, sleep, startBot, until } from './harness.mjs';
const bot = await startBot({ AGENTIC_TOOLS_TRUSTED: 'web_search,code_interpreter,file_search', AGENTIC_VECTOR_STORE_IDS: 'vs_team', MAX_JOBS_PER_USER: '1' });
await bot.mention('UADMIN', 'help');
const card = bot.calls.find(c => c.m === 'chat.postEphemeral');
ok(/Run Python calculations/.test(J(card.a.blocks)) && /Use multiple agents/.test(J(card.a.blocks)) && /Search the knowledge base/.test(J(card.a.blocks)), 'admin help advertises enabled gateway features');
await bot.mention('UMEM', 'multi do a task');
ok(bot.gateway.requests.length === 0 && bot.ephemerals().some(t => /cannot start multi-agent/.test(t)), 'multi-agent permission is enforced before inference');
bot.setMode('multi');
await bot.mention('UADMIN', 'multi compare algorithms');
const thread = bot.lastTs;
const first = bot.gateway.requests.at(-1);
ok(first.multi_agent?.enabled && !Object.hasOwn(first, 'max_tool_calls'), 'multi command sends native configuration without incompatible max_tool_calls');
ok(first.tools.some(tool => tool.type === 'code_interpreter' && tool.container.type === 'auto'), 'multi-agent request includes allowed interpreter');
ok(first.tools.find(tool => tool.type === 'file_search').vector_store_ids[0] === 'vs_team', 'file search is restricted to configured stores');
ok(!bot.calls.some(c => /child details/.test(J(c.a.blocks))) && bot.calls.some(c => /combined answer/.test(J(c.a.blocks))), 'Slack sees the root answer, not internal child messages');
await bot.mention('UADMIN', 'multi examine edge cases', thread);
ok(Boolean(bot.gateway.requests.at(-1).previous_response_id), 'multi follow-up continues the agent tree');
bot.setMode('code');
await bot.mention('UADMIN', 'calculate six times seven', thread);
ok(!bot.gateway.requests.at(-1).previous_response_id && !bot.gateway.requests.at(-1).multi_agent, 'standard requests have a separate memory chain from multi-agent requests');
ok(Boolean(bot.lastUpdate(a => /result is 42/.test(J(a.blocks)))), 'interpreter result reaches the normal Slack response');
bot.setMode('steerchat');
const running = bot.mention('UADMIN', 'long task');
await until(() => /long task/.test(bot.agentCalls().at(-1)?.prompt || ''));
await sleep(20);
const activeThread = bot.lastTs;
await bot.mention('UMEM', 'steer change the plan', activeThread);
ok(bot.ephemerals().some(t => /Only the person who started/.test(t)), 'another user cannot steer the job');
await bot.mention('UADMIN', 'steer focus on cost', activeThread);
await running;
ok(bot.ephemerals().some(t => /update has been applied/.test(t)), 'steering works even when the requester is at their one-job quota');
ok(bot.gateway.requests.at(-1).type === 'response.steer' && !Object.hasOwn(bot.gateway.requests.at(-1), 'stream_id'), 'steering uses the protocol control frame');
ok(Boolean(bot.lastUpdate(a => /updated answer/.test(J(a.blocks)))), 'the steering successor supplies the posted answer');
bot.setMode('sticker');
const beforeSticker = bot.gateway.requests.length;
await bot.mention('UMEM', 'make a dancing cat sticker');
const stickerUpload = bot.calls.find(c => c.m === 'files.uploadV2' && c.a.file_uploads?.some(f => f.filename === 'dancing-cat.gif'));
ok(stickerUpload?.a.file_uploads[0].file.subarray(0, 6).toString() === 'GIF89a', 'local function renders and uploads an actual GIF to Slack');
ok(bot.gateway.requests[beforeSticker].tools.some(tool => tool.name === 'create_sticker'), 'members with file permission receive the sticker function');
ok(bot.gateway.requests[beforeSticker + 1].input[0].type === 'function_call_output', 'sticker tool result continues inference over WebSocket');
bot.setMode('complete');
await bot.mention('UVIEW', 'make a sticker');
ok(!bot.gateway.requests.at(-1).tools.some(tool => tool.name === 'create_sticker'), 'viewers cannot invoke the local sticker function');
const { default: sharp } = await import('sharp');
const png = await sharp({ create: { width: 32, height: 32, channels: 4, background: { r: 255, g: 120, b: 20, alpha: 1 } } }).png().toBuffer();
const realFetch = globalThis.fetch;
globalThis.fetch = async () => new Response(png, { headers: { 'content-type': 'image/png' } });
bot.setMode('image-sticker');
const imageStart = bot.gateway.requests.length;
await bot.mention('UMEM', 'turn this image into a bouncing sticker', undefined, [{ id: 'FSTICKER', name: 'cat.png', size: png.length, url_private: 'https://files.slack.com/cat.png' }]);
globalThis.fetch = realFetch;
ok(bot.gateway.requests[imageStart].input[0].content.some(part => part.type === 'input_text' && /image_1/.test(part.text)), 'an uploaded image gets a request-scoped sticker ID');
ok(bot.calls.some(c => c.m === 'files.uploadV2' && c.a.file_uploads?.some(file => file.filename === 'uploaded-sticker.gif' && file.file.length < 256*1024)), 'prompt plus Slack image produces and uploads a small animated sticker');
finish();
