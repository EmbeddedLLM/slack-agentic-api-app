import { J, finish, ok, startBot, until } from './harness.mjs';
const bot = await startBot();
const { calls } = bot;
const card = () => bot.lastUpdate(a => /research_start/.test(J(a.blocks)));
const value = c => c.a.blocks.find(b => b.type === 'actions').elements[0].value;
await bot.mention('UMEM', 'research databases');
ok(bot.ephemerals().some(t => /only available to admins/.test(t)), 'members get an ordinary answer, not an approved research run');
await bot.mention('UADMIN', 'research compare vector databases');
const thread = bot.lastTs;
const plan = card();
ok(Boolean(plan) && /How many vectors/.test(J(plan.a.blocks)), 'admin receives a plan with clarifying questions');
ok(bot.agentCalls().at(-1).tools.length === 0 && bot.agentCalls().at(-1).store === false, 'planning uses a WebSocket response with no tools or persistent session');
await bot.click('research_start', value(plan), 'UMEM');
await until(() => bot.ephemerals().some(t => /Only admins/.test(t)));
ok(bot.ephemerals().some(t => /Only admins/.test(t)), 'research start checks access');
await bot.click('research_edit', value(plan));
ok(calls.some(c => c.m === 'views.open'), 'plan can be edited before approval');
await bot.click('research_start', value(plan));
await until(() => calls.some(c => c.m === 'chat.postMessage' && /Research finished/.test(c.a.text)));
ok(calls.some(c => c.m === 'files.uploadV2' && c.a.file_uploads.some(f => f.filename.endsWith('.md'))), 'finished research uploads Markdown report');
ok(calls.some(c => /PDF export is not installed/.test(J(c.a.blocks))), 'missing optional PDF renderer is reported while Markdown still succeeds');
const researchCalls = bot.agentCalls().filter(c => /Research this section now/.test(c.prompt));
ok(researchCalls.length === 2 && researchCalls.every(c => c.tools[0].type === 'web_search'), 'research uses gateway-owned web search');
ok(researchCalls[1].previous_response_id, 'research sections continue the stored response chain');
await bot.mention('UADMIN', 'which costs less?', thread);
ok(bot.agentCalls().at(-1).tools.length === 0 && /<research_evidence>/.test(bot.agentCalls().at(-1).prompt), 'follow-up uses saved evidence without a search');
await bot.mention('UADMIN', 'research another comparison');
const slowPlan = card();
bot.setMode('slow');
const beforeSlow = calls.length;
const running = bot.click('research_start', value(slowPlan));
const active = await until(() => calls.slice(beforeSlow).find(c => c.m === 'chat.postMessage' && /Research queued/.test(c.a.text)));
await until(() => bot.agentCalls().filter(c => /Research this section now/.test(c.prompt)).length === 3);
await bot.click('cancel_job', value(active));
await running;
const cancelled = await until(() => bot.lastUpdate(a => /research_resume/.test(J(a.blocks))));
ok(/Research cancelled by Ada Admin/.test(J(cancelled.a.blocks)), 'cancel leaves a Resume button');
await bot.click('research_resume', value(cancelled), 'UMEM', cancelled.a.ts);
ok(bot.ephemerals().some(t => /Only admins can resume/.test(t)), 'resume rechecks authorization');
bot.setMode('complete');
await bot.click('research_resume', value(cancelled), 'UADMIN', cancelled.a.ts);
await until(() => calls.filter(c => c.m === 'chat.postMessage' && /Research finished/.test(c.a.text)).length === 2);
ok(true, 'resume completes over a new WebSocket connection');
finish();
